#!/usr/bin/env node
/**
 * Writes src/version.ts from package.json, so the built module can report its
 * own name and version without importing package.json at runtime (which sits
 * outside tsconfig's rootDir). Runs as the first build step; the output is
 * committed so a fresh checkout typechecks before its first build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const packageUrl = new URL("../package.json", import.meta.url);
const outputUrl = new URL("../src/version.ts", import.meta.url);
const { name, version } = JSON.parse(readFileSync(packageUrl, "utf8"));

const source = [
  "// Generated by scripts/gen-version.mjs from package.json — do not edit.",
  `export const PACKAGE_NAME = ${JSON.stringify(name)};`,
  `export const VERSION = ${JSON.stringify(version)};`,
  "",
].join("\n");

let current = "";
try {
  current = readFileSync(outputUrl, "utf8");
} catch {
  // First run: nothing to compare against.
}
if (current !== source) {
  writeFileSync(outputUrl, source);
  console.log(`gen-version: wrote ${fileURLToPath(outputUrl)}`);
}
